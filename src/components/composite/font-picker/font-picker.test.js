import { test } from "node:test";
import assert from "node:assert/strict";
import { installDom } from "../../../testing/dom.ts";
const { document } = installDom({ url: "http://localhost/" });
const { h, render, signal } = await import("../../../index.ts");
const { locale } = await import("../../../core/i18n.ts");
locale.set("en");
const F = await import("./fonts.ts");
const { FontPicker } = await import("./index.ts");
const mount = (fn) => { const el = document.createElement("div"); document.body.appendChild(el); const dispose = render(fn, el); return { el, dispose }; };
const wait = (ms = 60) => new Promise((r) => setTimeout(r, ms));
const web = (family, category = "sans-serif", extra = {}) => ({ family, category, source: "web", weights: [400, 700], italics: [400], subsets: ["latin", "latin-ext"], added: 1, ...extra });
const CATALOG = [web("Inter"), web("Lora", "serif", { added: 9 }), web("Kiril Sans", "sans-serif", { subsets: ["cyrillic"], weights: [300] }), web("Fira Code", "monospace")];
const names = (el) => [...el.querySelectorAll("[role=option]")].map((o) => o.getAttribute("aria-label"));
const links = () => [...document.head.querySelectorAll("link[data-m-font]")].map((l) => l.href);
const button = (root, text) => [...root.querySelectorAll("button")].find((b) => b.textContent.trim() === text);

test("font model: catalog text, filter and order, stylesheet address, stack", async () => {
  const list = F.decodeCatalog("Roboto|0|e7|=|01|un\nLora|1|3c||0|fb\nRare|2|8|8|~10|0", "latin latin-ext " + Array.from({ length: 34 }, (_, i) => `s${i}`).join(" ") + " far");
  assert.equal(list[0].family, "Roboto");
  assert.equal(list[0].category, "sans-serif");
  assert.deepEqual(list[0].weights, [100, 200, 300, 400, 500, 600, 700, 800, 900]);
  assert.deepEqual(list[0].italics, list[0].weights, "= : the same weights in italic");
  assert.deepEqual(list[0].subsets, ["latin", "latin-ext"]);
  assert.equal(list[0].added, Number.parseInt("un", 36));
  assert.deepEqual(list[1].italics, [], "no italic");
  assert.equal(list[1].category, "serif");
  assert.deepEqual(list[2].subsets, ["far"], "a long subset code");
  assert.deepEqual(list[2].weights, [400]);
  assert.deepEqual(F.filterFonts(CATALOG, { query: "İNT" }).map((x) => x.family), ["Inter"], "case and accents folded");
  assert.deepEqual(F.filterFonts(CATALOG, { query: "o" }).map((x) => x.family), ["Lora", "Fira Code"], "the catalog order is kept");
  assert.deepEqual(F.filterFonts(CATALOG, { category: "serif" }).map((x) => x.family), ["Lora"]);
  assert.deepEqual(F.filterFonts(CATALOG, { subset: "cyrillic" }).map((x) => x.family), ["Kiril Sans"]);
  assert.deepEqual(F.filterFonts(CATALOG, { sort: "name" }).map((x) => x.family), ["Fira Code", "Inter", "Kiril Sans", "Lora"]);
  assert.equal(F.filterFonts(CATALOG, { sort: "newest" })[0].family, "Lora");
  assert.equal(F.nearestWeight(CATALOG[2], 400), 300);
  assert.equal(F.fontUrl("google", { family: "Open Sans", weights: [700, 400] }), "https://fonts.googleapis.com/css2?family=Open+Sans:wght@400;700&display=swap");
  assert.equal(F.fontUrl("/fonts/", { family: "Lora", weights: [400], italics: [400], text: "baa" }), "/fonts/css2?family=Lora:ital,wght@0,400;1,400&display=swap&text=ab");
  assert.equal(F.fontUrl((r) => `/f/${r.family}.css`, { family: "Lora", weights: [400] }), "/f/Lora.css");
  assert.equal(F.fontUrl(false, { family: "Lora", weights: [400] }), null);
  assert.equal(F.fontStack(CATALOG[1]), "\"Lora\", serif");
  assert.equal(F.fontStack(F.SYSTEM_FONTS[1]), "Arial, Helvetica, sans-serif");
  const real = await F.googleFonts();
  assert.ok(real.length > 1500 && real[0].family === "Roboto" && real.every((x) => x.weights.length), "the built-in catalog decodes");
});

test("FontPicker inline: groups, rows as options, search, pick with the CSS to use", async () => {
  const v = signal("Arial"), picks = [];
  const m = mount(() => h(FontPicker, { view: "inline", "bind:value": v, catalog: CATALOG, source: false, storageKey: false, onPick: (c) => picks.push(c) }));
  await wait();
  const box = m.el.querySelector("[role=listbox]");
  assert.equal(box.getAttribute("aria-label"), "Fonts");
  assert.ok(names(m.el).includes("Arial") && names(m.el).includes("Inter"), "system and web fonts in one list");
  assert.equal(m.el.querySelector("[role=option][aria-selected=true]").getAttribute("aria-label"), "Arial");
  assert.ok(m.el.textContent.includes("System") && m.el.textContent.includes("Web fonts"));
  const search = m.el.querySelector("input[type=search]");
  assert.equal(search.getAttribute("aria-controls"), box.id);
  search.value = "lor"; search.dispatchEvent(new globalThis.Event("input", { bubbles: true }));
  await wait();
  assert.deepEqual(names(m.el), ["Lora"]);
  assert.equal(search.getAttribute("aria-activedescendant"), m.el.querySelector("[role=option]").id, "the first match is the active option");
  search.dispatchEvent(new globalThis.KeyboardEvent("keydown", { key: "Enter", bubbles: true, cancelable: true }));
  await wait();
  assert.equal(v(), "Lora");
  assert.deepEqual({ ...picks.at(-1), font: null }, { family: "Lora", stack: "\"Lora\", serif", category: "serif", source: "web", weight: 400, italic: false, url: null, font: null });
  assert.equal(links().length, 0, "source false: nothing is requested");
  m.dispose();
});

test("FontPicker: consent before the first request, then previews load only the letters shown", async () => {
  const v = signal("");
  const m = mount(() => h(FontPicker, { view: "inline", "bind:value": v, catalog: CATALOG, system: false, askConsent: true, storageKey: false, specimen: false }));
  await wait(250);
  assert.equal(links().length, 0, "nothing is requested before the visitor agrees");
  const allow = button(m.el, "Allow");
  assert.ok(allow, "the notice has an Allow button");
  allow.click();
  await wait(250);
  const got = links();
  assert.equal(got.length, 4, "one small request per row in view");
  assert.ok(got.includes("https://fonts.googleapis.com/css2?family=Inter:wght@400&display=swap&text=" + encodeURIComponent("Ienrt")), got.join(" "));
  assert.ok(got.some((u) => u.includes("Kiril+Sans:wght@300")), "the nearest weight the family has");
  assert.equal(m.el.querySelector(".m-fp-consent"), null, "the notice is gone");
  m.dispose();
});

test("FontPicker: parts can be turned off, own texts, favourites", async () => {
  const fav = [];
  const m = mount(() => h(FontPicker, { view: "inline", catalog: CATALOG, source: false, storageKey: false, search: false, categories: false, sorts: false, subsets: false, count: false, specimen: false, labels: { system: "Cihaz", web: "Kitaplık" }, onFavorite: (f, on) => fav.push([f, on]) }));
  await wait();
  assert.equal(m.el.querySelector("input[type=search]"), null);
  assert.equal(m.el.querySelector(".m-fp-cats"), null);
  assert.equal(m.el.querySelector(".m-fp-specimen"), null);
  assert.ok(m.el.textContent.includes("Cihaz") && m.el.textContent.includes("Kitaplık"));
  const star = m.el.querySelector(".m-fp-star");
  assert.equal(star.getAttribute("aria-pressed"), "false");
  star.click();
  await wait();
  assert.deepEqual(fav, [["System UI", true]]);
  assert.ok(m.el.textContent.includes("Favorites"), "a Favourites group appears");
  m.dispose();
});

test("FontPicker popover and dialog: a button with the name, the panel opens on a click", async () => {
  const m = mount(() => h(FontPicker, { value: "Georgia", catalog: CATALOG, source: false, storageKey: false }));
  const btn = m.el.querySelector("button.m-fp-trigger");
  assert.ok(btn.textContent.includes("Georgia"));
  assert.equal(btn.getAttribute("aria-expanded"), "false");
  btn.click();
  await wait();
  assert.equal(btn.getAttribute("aria-expanded"), "true");
  assert.ok(document.body.querySelector(".m-fp-pop [role=listbox]"), "the list is in the popover");
  m.dispose();
  const open = signal(true);
  const d = mount(() => h(FontPicker, { view: "dialog", value: "Georgia", catalog: CATALOG, source: false, storageKey: false, open, labels: { done: "Tamam" } }));
  await wait();
  const dlg = document.body.querySelector("[role=dialog]");
  assert.ok(dlg.querySelector("[role=listbox]") && dlg.textContent.includes("Tamam"));
  button(dlg, "Tamam").click();
  await wait();
  assert.equal(open(), false);
  d.dispose();
});

#!/usr/bin/env node
// Writes the shared files from the component folders (src/components/<category>/<name>/), so nobody edits them by hand
// and parallel branches that add folders do not conflict. The category list is src/components/categories.ts:
//   src/components/index.ts              barrel of every component (re-exported by hadi-march/ui)
//   src/components/<category>/index.ts   one barrel per category: the subpath hadi-march/<category>
//   src/components/registry.gen.ts       catalogue: name, folder, category, meta, lazy demo / playground loaders
//   docs/components.md                   component catalogue by category, for people and AI (each docs.md + meta.ts)
//   AI_INSTRUCTIONS.md                   the catalogue table between the <!-- components:begin/end --> markers
//   package.json                         "exports" has "./<category>" for every category
//   node tools/gen-registry.js          write
//   node tools/gen-registry.js --check  fail (exit 1) when a written file is out of date or a folder is malformed
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const REQUIRED = ["index.ts", "docs.md", "demo.tsx", "playground.ts", "meta.ts"];
const isDir = (p) => existsSync(p) && statSync(p).isDirectory();

/** The category list (src/components/categories.ts). */
export async function categories(root = ROOT) {
  return (await import(pathToFileURL(join(root, "src/components/categories.ts")).href)).CATEGORIES;
}

/**
 * Categories reachable only through their own subpath (hadi-march/landing), not through the ui barrel: with code
 * splitting, a barrel that re-exports them puts their code in a chunk shared with every page importing hadi-march/ui.
 */
const OUTSIDE_UI = new Set(["landing"]);

/** Subpaths that existed before the categories: their module index re-exports the category barrel instead. */
const OWN_MODULE = { forms: "src/forms/index.ts", data: "src/data/index.ts", motion: "src/motion/index.ts" };

/** Component folders with their meta, sorted by name. `stray` lists folders outside a known category. */
export async function components(root = ROOT) {
  const dir = join(root, "src/components");
  const out = [];
  const stray = [];
  if (!existsSync(dir)) return Object.assign(out, { stray });
  const ids = new Set((await categories(root)).map((c) => c.id));
  for (const top of readdirSync(dir).sort()) {
    const p = join(dir, top);
    if (!isDir(p)) continue;
    if (!ids.has(top)) { stray.push(top); continue; }
    for (const name of readdirSync(p).sort()) {
      const q = join(p, name);
      if (!isDir(q)) continue;
      const meta = existsSync(join(q, "meta.ts")) ? (await import(pathToFileURL(join(q, "meta.ts")).href)).default : null;
      out.push({ folder: `${top}/${name}`, category: top, name, meta, files: readdirSync(q), docs: existsSync(join(q, "docs.md")) ? readFileSync(join(q, "docs.md"), "utf8") : "" });
    }
  }
  out.sort((a, b) => a.name.localeCompare(b.name));
  return Object.assign(out, { stray });
}

const HEAD = "// GENERATED by tools/gen-registry.js from src/components/<category>/<name>/ — do not edit.\n";
const firstCode = (md) => md.match(/```\w*\n([\s\S]*?)```/)?.[1].trim() ?? "";
const firstPara = (md) => md.split(/\n\n/).find((b) => b.trim() && !b.startsWith("#") && !b.startsWith("```"))?.replace(/\s+/g, " ").trim() ?? "";
const nameOf = (c) => c.meta?.name ?? c.name;
const anchor = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

/** The generated files' contents, keyed by path relative to the repo. */
export async function generate(root = ROOT) {
  const list = await components(root);
  const cats = await categories(root);
  const files = {};
  files["src/components/index.ts"] = HEAD + list.filter((c) => !OUTSIDE_UI.has(c.category)).map((c) => `export * from "./${c.folder}/index.ts";\n`).join("");
  for (const cat of cats) {
    const own = list.filter((c) => c.category === cat.id);
    files[`src/components/${cat.id}/index.ts`] = HEAD + `// ${cat.title}: ${cat.desc} Import: hadi-march/${cat.id}\n` +
      (own.length ? own.map((c) => `export * from "./${c.name}/index.ts";\n`).join("") : "export {};\n");
  }
  files["src/components/registry.gen.ts"] = HEAD + `import type { ComponentMeta, PlaygroundSpec } from "./meta.ts";\n` +
    list.map((c, i) => `import m${i} from "./${c.folder}/meta.ts";\n`).join("") +
    `\nexport interface RegistryEntry { folder: string; meta: ComponentMeta; /** First code block of docs.md (the Code tab). */ code: string; demo: () => Promise<{ default: (p: { values: never }) => unknown; code?: string }>; playground: () => Promise<{ default: PlaygroundSpec<never> }> }\n` +
    `export const registry: readonly RegistryEntry[] = [\n` +
    list.map((c, i) => `  { folder: "${c.folder}", meta: m${i}, code: ${JSON.stringify(firstCode(c.docs))}, demo: () => import("./${c.folder}/demo.tsx"), playground: () => import("./${c.folder}/playground.ts") },\n`).join("") + `];\n`;

  // catalogue by category (menu order), "composed of" links to the parts
  const byName = new Map(list.map((c) => [nameOf(c), c]));
  const part = (n) => (byName.has(n) ? `[${n}](#${anchor(n)})` : n);
  const row = (c, link) => `| ${nameOf(c)} | ${c.meta?.status ?? "?"} | ${c.meta?.summary ?? firstPara(c.docs)} | ${(c.meta?.composedOf ?? []).map(link ? part : (n) => n).join(", ") || "—"} |`;
  const filled = cats.filter((cat) => list.some((c) => c.category === cat.id));
  const table = (link) => filled.map((cat) => `### ${cat.title} — \`hadi-march/${cat.id}\`\n\n| Component | Status | What | Composed of |\n|---|---|---|---|\n` +
    list.filter((c) => c.category === cat.id).map((c) => row(c, link)).join("\n") + "\n").join("\n");
  files["docs/components.md"] = `<!-- GENERATED by tools/gen-registry.js from src/components/<category>/<name>/docs.md and meta.ts — do not edit. -->\n# Components\n\n` +
    `Grouped by category (src/components/categories.ts). Each category is a subpath: \`import { Chip } from "hadi-march/actions"\`; ` +
    `\`hadi-march/ui\` re-exports every component.\n\n${table(true)}\n` +
    list.map((c) => `## ${nameOf(c)}\n\n${firstPara(c.docs)}\n\n` +
      ((c.meta?.composedOf ?? []).length ? `Composed of: ${c.meta.composedOf.map(part).join(", ")}\n\n` : "") +
      `\`\`\`tsx\n${firstCode(c.docs)}\n\`\`\`\n\nFull page: src/components/${c.folder}/docs.md\n`).join("\n");
  const ai = readFileSync(join(root, "AI_INSTRUCTIONS.md"), "utf8");
  const block = `<!-- components:begin (generated by tools/gen-registry.js) -->\n${table(false)}<!-- components:end -->`;
  files["AI_INSTRUCTIONS.md"] = /<!-- components:begin[\s\S]*?<!-- components:end -->/.test(ai) ? ai.replace(/<!-- components:begin[\s\S]*?<!-- components:end -->/, block) : `${ai.trimEnd()}\n\n## Component catalogue (folders in src/components)\n\n${block}\n`;

  // subpaths: hadi-march/<category>; an older module of the same name re-exports the category barrel
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  let changed = false;
  for (const cat of cats) {
    const own = OWN_MODULE[cat.id];
    if (own) {
      const line = `export * from "../components/${cat.id}/index.ts";`;
      const text = readFileSync(join(root, own), "utf8");
      if (!text.includes(line)) files[own] = `${text.trimEnd()}\n// components of the "${cat.id}" category (src/components/${cat.id}, generated barrel)\n${line}\n`;
    } else if (pkg.exports[`./${cat.id}`] !== `./src/components/${cat.id}/index.ts`) {
      pkg.exports[`./${cat.id}`] = `./src/components/${cat.id}/index.ts`;
      changed = true;
    }
  }
  if (changed) files["package.json"] = JSON.stringify(pkg, null, 2) + "\n";
  return { files, list };
}

/** Exported names of hadi-march and hadi-march/ui (a part named in composedOf may still live there while folders move). */
function uiExports(root) {
  const text = ["src/index.ts", "src/ui/index.ts", "src/forms/index.ts"].map((f) => readFileSync(join(root, f), "utf8")).join("\n");
  return new Set([...text.matchAll(/^export\s*\{([^}]*)\}/gm)].flatMap((m) => m[1].split(",").map((s) => s.trim().split(/\s+as\s+/).pop()).filter(Boolean)));
}

/** Folder problems: missing files, a missing or wrong category, composedOf rules (a composite names its parts, and
 *  every part is a registered component or an export of hadi-march/ui). */
export function shapeProblems(list, root = ROOT) {
  const out = (list.stray ?? []).map((f) => `src/components/${f}: not a category folder (src/components/categories.ts); move it to src/components/<category>/${f}/`);
  const names = new Set(list.map(nameOf));
  const ui = uiExports(root);
  for (const c of list) {
    for (const f of REQUIRED) if (!c.files.includes(f)) out.push(`${c.folder}: missing ${f}`);
    if (!c.files.some((f) => f.endsWith(".test.js"))) out.push(`${c.folder}: missing ${c.name}.test.js`);
    if (!c.meta) continue;
    if (!c.meta.category) out.push(`${c.folder}: meta.category is missing (one of src/components/categories.ts)`);
    else if (c.meta.category !== c.category) out.push(`${c.folder}: meta.category is "${c.meta.category}" but the folder is in ${c.category}/`);
    if (!Array.isArray(c.meta.composedOf)) { out.push(`${c.folder}: meta.composedOf must be an array`); continue; }
    if (c.category === "composite" && !c.meta.composedOf.length) out.push(`${c.folder}: a composite component names its parts in meta.composedOf`);
    for (const p of c.meta.composedOf) if (!names.has(p) && !ui.has(p)) out.push(`${c.folder}: composedOf "${p}" is not a component`);
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { files, list } = await generate();
  const problems = shapeProblems(list);
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const p = join(ROOT, rel);
    const now = existsSync(p) ? readFileSync(p, "utf8") : null;
    if (now === text) continue;
    if (check) { console.error(`✖ ${rel} is out of date: run node tools/gen-registry.js`); stale++; }
    else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); console.log(`✔ ${rel}`); }
  }
  for (const p of problems) console.error(`✖ ${p}`);
  if (stale || problems.length) process.exit(1);
  console.log(`${list.length} component folder(s)${check ? ": up to date" : ""}`);
}

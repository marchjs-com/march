#!/usr/bin/env node
// Writes the shared files from the component folders (src/components/<category>/<name>/), so nobody edits them by hand
// and parallel branches that add folders do not conflict. The category list is src/components/categories.ts:
//   src/components/index.ts              barrel of every component (re-exported by march/ui)
//   src/components/<category>/index.ts   one barrel per category: the subpath march/<category>
//   docs/components.md                   component catalogue by category, for people and AI (each docs.md + meta.ts)
//   AI_INSTRUCTIONS.md                   the catalogue table between the <!-- components:begin/end --> markers
//   package.json                         "exports" has "./<category>" for every category and "./components/<category>/<name>"
//                                        for every large component kept out of the barrels (meta.barrel false)
//   node tools/gen-registry.js          write
//   node tools/gen-registry.js --check  fail (exit 1) when a written file is out of date or a folder is malformed
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const REQUIRED = ["index.ts", "docs.md", "meta.ts"];
const isDir = (p) => existsSync(p) && statSync(p).isDirectory();

/** The category list (src/components/categories.ts). */
export async function categories(root = ROOT) {
  return (await import(pathToFileURL(join(root, "src/components/categories.ts")).href)).CATEGORIES;
}

/**
 * Categories reachable only through their own subpath (march/landing), not through the ui barrel: a website's
 * blocks are a page of their own, and a barrel re-export would put them in the static graph of every ui page.
 */
const OUTSIDE_UI = new Set(["landing"]);

/** Subpaths that existed before the categories: their module index re-exports the category barrel instead. */
const OWN_MODULE = { forms: "src/forms/index.ts", data: "src/data/index.ts", motion: "src/motion/index.ts" };

/** Component folders with their meta, sorted by name. `stray` lists folders outside a known category. */
export async function components(root = ROOT) {
  const dir = join(root, "src/components");
  const out = [];
  const stray = [];
  if (!existsSync(dir)) return Object.assign(out, { stray });
  const ids = new Set((await categories(root)).map((c) => c.id));
  for (const top of readdirSync(dir).sort()) {
    const p = join(dir, top);
    if (!isDir(p)) continue;
    if (!ids.has(top)) { stray.push(top); continue; }
    for (const name of readdirSync(p).sort()) {
      const q = join(p, name);
      if (!isDir(q)) continue;
      const meta = existsSync(join(q, "meta.ts")) ? (await import(pathToFileURL(join(q, "meta.ts")).href)).default : null;
      out.push({ folder: `${top}/${name}`, category: top, name, meta, files: readdirSync(q), docs: existsSync(join(q, "docs.md")) ? readFileSync(join(q, "docs.md"), "utf8") : "" });
    }
  }
  out.sort((a, b) => a.name.localeCompare(b.name, "en"));
  return Object.assign(out, { stray });
}

/** Names a component's index.ts exports itself: declarations and `export { … }` lists (`export *` is not followed). name → type only? */
const exportedNames = (src) => {
  const out = new Map();
  for (const m of src.matchAll(/^export\s+(?:declare\s+)?(type|interface|const|let|function\*?|async\s+function|class|enum)\s+([A-Za-z_$][\w$]*)/gm)) out.set(m[2], m[1] === "type" || m[1] === "interface");
  for (const m of src.matchAll(/^export\s+(type\s+)?\{([^}]*)\}/gm)) {
    for (const part of m[2].split(",")) {
      const p = part.trim();
      if (!p) continue;
      out.set(p.replace(/^type\s+/, "").split(/\s+as\s+/).pop().trim(), !!m[1] || p.startsWith("type "));
    }
  }
  return out;
};
/**
 * `export *` from two components that export the same name is ambiguous (TS2308). The barrel then names the owner
 * explicitly: the first folder (by path) keeps the name; the other component is reached by its own specific name
 * (TerminalCommand) or its own path. `path(c)` is the import path of a component from the barrel.
 */
const explicitExports = (root, list, path) => {
  const seen = new Map();
  const lines = [];
  for (const c of [...list].sort((a, b) => a.folder.localeCompare(b.folder, "en"))) {
    const file = join(root, "src/components", c.folder, "index.ts");
    if (!existsSync(file)) continue;
    for (const [name, isType] of exportedNames(readFileSync(file, "utf8"))) {
      const first = seen.get(name);
      if (!first) seen.set(name, { c, isType, done: false });
      else if (!first.done) { first.done = true; lines.push(`export ${first.isType ? "type " : ""}{ ${name} } from "${path(first.c)}";\n`); }
    }
  }
  return lines.sort().join("");
};

const HEAD = "// GENERATED by tools/gen-registry.js from src/components/<category>/<name>/ — do not edit.\n";
const firstCode = (md) => md.match(/```\w*\n([\s\S]*?)```/)?.[1].trim() ?? "";
const firstPara = (md) => md.split(/\n\n/).find((b) => b.trim() && !b.startsWith("#") && !b.startsWith("```"))?.replace(/\s+/g, " ").trim() ?? "";
const nameOf = (c) => c.meta?.name ?? c.name;
const anchor = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

/** The class of a component's root element: meta.root, else the first class its stylesheet styles (tools find the
 *  component in a page by it; tools/cdn-data.mjs publishes it in data/components.json). */
export function rootClass(c, root = ROOT) {
  if (c.meta?.root) return c.meta.root;
  const dir = join(root, "src/components", c.folder);
  const css = existsSync(dir) ? readdirSync(dir).find((f) => f.endsWith(".css")) : null;
  return css ? /^\.(m-[a-z0-9-]+)/m.exec(readFileSync(join(dir, css), "utf8").replace(/\/\*[\s\S]*?\*\//g, ""))?.[1] ?? null : null;
}

/** The generated files' contents, keyed by path relative to the repo. */
export async function generate(root = ROOT) {
  const list = await components(root);
  const cats = await categories(root);
  const files = {};
  // large components (meta.barrel === false) stay out of the barrels: import them from march/components/<folder> (an
  // export of its own, below);
  // a component with its own package entry (meta.entry, e.g. "march/flow") too: pages that import march/ui
  // must not reach a heavy one-page feature (esbuild places code by reachability)
  const barrel = list.filter((c) => c.meta?.barrel !== false && !c.meta?.entry);
  // categories with their own subpath only (march/landing) stay out of the ui barrel, in their category barrel
  const inUi = barrel.filter((c) => !OUTSIDE_UI.has(c.category));
  files["src/components/index.ts"] = HEAD + inUi.map((c) => `export * from "./${c.folder}/index.ts";
`).join("") + explicitExports(root, inUi, (c) => `./${c.folder}/index.ts`);
  for (const cat of cats) {
    const own = barrel.filter((c) => c.category === cat.id);
    files[`src/components/${cat.id}/index.ts`] = HEAD + `// ${cat.title}: ${cat.desc} Import: march/${cat.id}\n` +
      (own.length ? own.map((c) => `export * from "./${c.name}/index.ts";\n`).join("") + explicitExports(root, own, (c) => `./${c.name}/index.ts`) : "export {};\n");
  }
  // Each component's props table, notes and accessibility: docs.md's "## Props" table (and the lines after
  // it) and "## Accessibility", one JSON per category (`comp`, not written here: tools/cdn-data.mjs publishes them as
  // data/comp/<category>.json, which sites read for a component's Props and Accessibility tabs).
  const comp = {};
  const mdSection = (md, title) => md.match(new RegExp(`^## ${title}[^\\n]*\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))`, "m"))?.[1].trim() ?? "";
  const cells = (line) => line.trim().replace(/^\||\|$/g, "").split(/(?<!\\)\|/).map((x) => x.trim().replace(/\\\|/g, "|"));
  const propsOf = (md) => {
    const sec = mdSection(md, "Props"), lines = sec.split("\n"), rows = [], rest = [];
    let head = null;
    for (const line of lines) {
      if (/^\s*\|/.test(line)) {
        const c = cells(line);
        if (!head) { head = c.map((x) => x.toLowerCase()); continue; }
        if (c.every((x) => /^:?-+:?$/.test(x) || !x)) continue;
        const at = (k, d) => { const i = head.findIndex((h) => h.startsWith(k)); return i >= 0 ? c[i] ?? "" : d; };
        const di = head.findIndex((h) => !/^(prop|type|default)/.test(h));
        rows.push([at("prop", c[0] ?? ""), at("type", c[1] ?? ""), at("default", ""), di >= 0 ? c.slice(di).join(" | ") : ""]);
      } else if (rows.length || !head) rest.push(line);
    }
    return { props: rows, notes: rest.join("\n").trim() };
  };
  const docsByCat = {};
  for (const c of list) {
    const { props, notes } = propsOf(c.docs);
    (docsByCat[c.category] ??= {})[c.folder] = { props, notes, a11y: mdSection(c.docs, "Accessibility") };
  }
  for (const [cat, all] of Object.entries(docsByCat)) comp[`comp/${cat}.json`] = JSON.stringify(all) + "\n";
  // catalogue by category (menu order), "composed of" links to the parts
  const byName = new Map(list.map((c) => [nameOf(c), c]));
  const part = (n) => (byName.has(n) ? `[${n}](#${anchor(n)})` : n);
  const row = (c, link) => `| ${nameOf(c)} | ${c.meta?.status ?? "?"} | ${c.meta?.summary ?? firstPara(c.docs)} | ${(c.meta?.composedOf ?? []).map(link ? part : (n) => n).join(", ") || "—"} |`;
  const filled = cats.filter((cat) => list.some((c) => c.category === cat.id));
  const table = (link) => filled.map((cat) => `### ${cat.title} — \`march/${cat.id}\`\n\n| Component | Status | What | Composed of |\n|---|---|---|---|\n` +
    list.filter((c) => c.category === cat.id).map((c) => row(c, link)).join("\n") + "\n").join("\n");
  files["docs/components.md"] = `<!-- GENERATED by tools/gen-registry.js from src/components/<category>/<name>/docs.md and meta.ts — do not edit. -->\n# Components\n\n` +
    `Grouped by category (src/components/categories.ts). Each category is a subpath: \`import { Chip } from "march/actions"\`; ` +
    `\`march/ui\` re-exports every component.\n\n${table(true)}\n` +
    list.map((c) => `## ${nameOf(c)}\n\n${firstPara(c.docs)}\n\n` +
      ((c.meta?.composedOf ?? []).length ? `Composed of: ${c.meta.composedOf.map(part).join(", ")}\n\n` : "") +
      `\`\`\`tsx\n${firstCode(c.docs)}\n\`\`\`\n\nFull page: src/components/${c.folder}/docs.md\n`).join("\n");
  const ai = readFileSync(join(root, "AI_INSTRUCTIONS.md"), "utf8");
  const block = `<!-- components:begin (generated by tools/gen-registry.js) -->\n${table(false)}<!-- components:end -->`;
  files["AI_INSTRUCTIONS.md"] = /<!-- components:begin[\s\S]*?<!-- components:end -->/.test(ai) ? ai.replace(/<!-- components:begin[\s\S]*?<!-- components:end -->/, block) : `${ai.trimEnd()}\n\n## Component catalogue (folders in src/components)\n\n${block}\n`;

  // subpaths: march/<category>; an older module of the same name re-exports the category barrel
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  let changed = false;
  for (const cat of cats) {
    const own = OWN_MODULE[cat.id];
    if (own) {
      const line = `export * from "../components/${cat.id}/index.ts";`;
      const text = readFileSync(join(root, own), "utf8");
      if (!text.includes(line)) files[own] = `${text.trimEnd()}\n// components of the "${cat.id}" category (src/components/${cat.id}, generated barrel)\n${line}\n`;
    } else if (pkg.exports[`./${cat.id}`] !== `./src/components/${cat.id}/index.ts`) {
      pkg.exports[`./${cat.id}`] = `./src/components/${cat.id}/index.ts`;
      changed = true;
    }
  }
  // a large component (barrel: false) has its own subpath, march/components/<category>/<name>; no other file under
  // src/components is reachable from outside (no wildcard)
  const large = new Set(list.filter((c) => c.meta?.barrel === false && !c.meta?.entry).map((c) => `./components/${c.folder}`));
  for (const key of Object.keys(pkg.exports)) if (key.startsWith("./components/") && !large.has(key)) { delete pkg.exports[key]; changed = true; }
  for (const key of large) if (pkg.exports[key] !== `./src/${key.slice(2)}/index.ts`) { pkg.exports[key] = `./src/${key.slice(2)}/index.ts`; changed = true; }
  if (changed) files["package.json"] = JSON.stringify(pkg, null, 2) + "\n";
  return { files, list, comp };
}

/** Exported names of march, march/ui, march/router and march/table (a part named in composedOf may still live there while folders move). */
function uiExports(root) {
  const text = ["src/index.ts", "src/ui/index.ts", "src/forms/index.ts", "src/router/index.ts", "src/router/router.ts", "src/table/index.ts"].map((f) => readFileSync(join(root, f), "utf8")).join("\n");
  return new Set([
    ...[...text.matchAll(/^export\s*\{([^}]*)\}/gm)].flatMap((m) => m[1].split(",").map((s) => s.trim().split(/\s+as\s+/).pop()).filter(Boolean)),
    ...[...text.matchAll(/^export\s+(?:function|const|class)\s+([A-Z][\w$]*)/gm)].map((m) => m[1]),
  ]);
}

/** Folder problems: missing files, a missing or wrong category, composedOf rules (a composite names its parts, and
 *  every part is a registered component or an export of march/ui). */
export function shapeProblems(list, root = ROOT) {
  const out = (list.stray ?? []).map((f) => `src/components/${f}: not a category folder (src/components/categories.ts); move it to src/components/<category>/${f}/`);
  const names = new Set(list.map(nameOf));
  const ui = uiExports(root);
  for (const c of list) {
    for (const f of REQUIRED) if (!c.files.includes(f)) out.push(`${c.folder}: missing ${f}`);
    if (!c.files.some((f) => f.endsWith(".test.js"))) out.push(`${c.folder}: missing ${c.name}.test.js`);
    if (!c.meta) continue;
    if (!c.meta.category) out.push(`${c.folder}: meta.category is missing (one of src/components/categories.ts)`);
    else if (c.meta.category !== c.category) out.push(`${c.folder}: meta.category is "${c.meta.category}" but the folder is in ${c.category}/`);
    if (!Array.isArray(c.meta.composedOf)) { out.push(`${c.folder}: meta.composedOf must be an array`); continue; }
    if (c.category === "composite" && !c.meta.composedOf.length) out.push(`${c.folder}: a composite component names its parts in meta.composedOf`);
    for (const p of c.meta.composedOf) if (!names.has(p) && !ui.has(p)) out.push(`${c.folder}: composedOf "${p}" is not a component`);
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { files, list } = await generate();
  const problems = shapeProblems(list);
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const p = join(ROOT, rel);
    const now = existsSync(p) ? readFileSync(p, "utf8") : null;
    if (now === text) continue;
    if (check) { console.error(`✖ ${rel} is out of date: run node tools/gen-registry.js`); stale++; }
    else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); console.log(`✔ ${rel}`); }
  }
  // demo modules of an earlier slicing (fewer cards, a page renamed) go away
  const dir = join(ROOT, "src/components");
  for (const f of readdirSync(dir).filter((f) => (f.endsWith(".demos.gen.ts") || f.endsWith(".kit.gen.ts")) && !files[`src/components/${f}`])) {
    if (check) { console.error(`✖ src/components/${f} is stale: run node tools/gen-registry.js`); stale++; }
    else { unlinkSync(join(dir, f)); console.log(`✖ removed src/components/${f}`); }
  }
  for (const p of problems) console.error(`✖ ${p}`);
  if (stale || problems.length) process.exit(1);
  console.log(`${list.length} component folder(s)${check ? ": up to date" : ""}`);
}

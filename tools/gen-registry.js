#!/usr/bin/env node
// Writes the shared files from the component folders (src/components/<category>/<name>/), so nobody edits them by hand
// and parallel branches that add folders do not conflict. The category list is src/components/categories.ts:
//   src/components/index.ts              barrel of every component (re-exported by hadi-march/ui)
//   src/components/<category>/index.ts   one barrel per category: the subpath hadi-march/<category>
//   src/components/registry.gen.ts       catalogue: name, folder, category, meta, lazy demo / playground loaders
//   docs/components.md                   component catalogue by category, for people and AI (each docs.md + meta.ts)
//   AI_INSTRUCTIONS.md                   the catalogue table between the <!-- components:begin/end --> markers
//   package.json                         "exports" has "./<category>" for every category
//   node tools/gen-registry.js          write
//   node tools/gen-registry.js --check  fail (exit 1) when a written file is out of date or a folder is malformed
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync, mkdirSync, unlinkSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const REQUIRED = ["index.ts", "docs.md", "demo.tsx", "playground.ts", "meta.ts"];
const isDir = (p) => existsSync(p) && statSync(p).isDirectory();

/** The category list (src/components/categories.ts). */
export async function categories(root = ROOT) {
  return (await import(pathToFileURL(join(root, "src/components/categories.ts")).href)).CATEGORIES;
}

/**
 * Categories reachable only through their own subpath (hadi-march/landing), not through the ui barrel: a website's
 * blocks are a page of their own, and a barrel re-export would put them in the static graph of every ui page.
 */
const OUTSIDE_UI = new Set(["landing"]);

/** Subpaths that existed before the categories: their module index re-exports the category barrel instead. */
const OWN_MODULE = { forms: "src/forms/index.ts", data: "src/data/index.ts", motion: "src/motion/index.ts" };

/** Component folders with their meta, sorted by name. `stray` lists folders outside a known category. */
export async function components(root = ROOT) {
  const dir = join(root, "src/components");
  const out = [];
  const stray = [];
  if (!existsSync(dir)) return Object.assign(out, { stray });
  const ids = new Set((await categories(root)).map((c) => c.id));
  for (const top of readdirSync(dir).sort()) {
    const p = join(dir, top);
    if (!isDir(p)) continue;
    if (!ids.has(top)) { stray.push(top); continue; }
    for (const name of readdirSync(p).sort()) {
      const q = join(p, name);
      if (!isDir(q)) continue;
      const meta = existsSync(join(q, "meta.ts")) ? (await import(pathToFileURL(join(q, "meta.ts")).href)).default : null;
      out.push({ folder: `${top}/${name}`, category: top, name, meta, files: readdirSync(q), docs: existsSync(join(q, "docs.md")) ? readFileSync(join(q, "docs.md"), "utf8") : "" });
    }
  }
  out.sort((a, b) => a.name.localeCompare(b.name));
  return Object.assign(out, { stray });
}

const HEAD = "// GENERATED by tools/gen-registry.js from src/components/<category>/<name>/ — do not edit.\n";
const firstCode = (md) => md.match(/```\w*\n([\s\S]*?)```/)?.[1].trim() ?? "";
const firstPara = (md) => md.split(/\n\n/).find((b) => b.trim() && !b.startsWith("#") && !b.startsWith("```"))?.replace(/\s+/g, " ").trim() ?? "";
const nameOf = (c) => c.meta?.name ?? c.name;
const anchor = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

/** The generated files' contents, keyed by path relative to the repo. */
export async function generate(root = ROOT) {
  const list = await components(root);
  const cats = await categories(root);
  const files = {};
  // large components (meta.barrel === false) stay out of the barrels: import them from hadi-march/components/<folder>;
  // a component with its own package entry (meta.entry, e.g. "hadi-march/flow") too: pages that import hadi-march/ui
  // must not reach a heavy one-page feature (esbuild places code by reachability)
  const barrel = list.filter((c) => c.meta?.barrel !== false && !c.meta?.entry);
  // categories with their own subpath only (hadi-march/landing) stay out of the ui barrel, in their category barrel
  files["src/components/index.ts"] = HEAD + barrel.filter((c) => !OUTSIDE_UI.has(c.category)).map((c) => `export * from "./${c.folder}/index.ts";
`).join("");
  for (const cat of cats) {
    const own = barrel.filter((c) => c.category === cat.id);
    files[`src/components/${cat.id}/index.ts`] = HEAD + `// ${cat.title}: ${cat.desc} Import: hadi-march/${cat.id}\n` +
      (own.length ? own.map((c) => `export * from "./${c.name}/index.ts";\n`).join("") : "export {};\n");
  }
  // Demos shown on the same showcase page load together, up to GROUP per lazy module (<page>[-n].demos.gen.ts): one
  // small chunk per demo would fall under the 10 KB chunk floor and fold into the registry's parent group, which every
  // page with a component card loads; one module for a page with many cards would pass the lazy part budget. Members
  // are in folder-name order, so related folders (chat-…, story-…) usually share a module. A page with a single
  // component card keeps its direct import. meta.demoGroup names a family that loads together; the page's building
  // blocks share one kit (<page>.kit.gen.ts).
  const GROUP = 3;
  // pages whose demos are heavier than the usual card may get fewer per module. /forms is not one: its demo parts weigh
  // mostly the input code the /forms page already loads (a part row counts it too), two per module measured as heavy as
  // three (28–30 KB) and made 13 parts instead of 9, each splitting the shared code further
  const GROUP_OF = {};
  const pages = new Map();
  // a large component (barrel: false) keeps its own demo module: its code alone is over the chunk floor, and grouping
  // it would make every card of the page download it
  for (const c of list) if (c.meta?.showcase && c.meta?.barrel !== false && !c.meta?.entry) pages.set(c.meta.showcase, [...(pages.get(c.meta.showcase) ?? []), c]);
  const groupOf = new Map();
  for (const [page, all] of pages) {
    if (all.length < 2) continue;
    const base = page.replace(/^\//, "").replace(/[^\w-]+/g, "-") || "home";
    const named = new Map(), rest = [];
    for (const c of all) if (c.meta?.demoGroup) named.set(c.meta.demoGroup, [...(named.get(c.meta.demoGroup) ?? []), c]); else rest.push(c);
    const parts = [...named].map(([g, members]) => ({ name: `${base}-${g}`, members }));
    const slices = Math.ceil(rest.length / (GROUP_OF[page] ?? GROUP));
    for (let s = 0; s < slices; s++) parts.push({ name: `${base}${slices > 1 || parts.length ? `-${s + 1}` : ""}`, members: rest.slice(Math.floor((s * rest.length) / slices), Math.floor(((s + 1) * rest.length) / slices)) });
    // landing blocks are many and large: only the ones other blocks are built from (composedOf) go in the kit, the rest
    // stay in their family module; the category's demo data (<category>/demo-kit.tsx) rides in the kit too
    const usedByOthers = (c) => all.some((o) => o !== c && (o.meta?.composedOf ?? []).includes(c.meta?.name));
    const blocks = parts.length > 1 ? all.filter((c) => c.category && c.category !== "composite" && (c.category !== "landing" || usedByOthers(c))) : [];
    const demoKits = [...new Set(blocks.map((c) => c.category))].filter((k) => existsSync(join(root, "src/components", k, "demo-kit.tsx")));
    const kit = blocks.length > 1 ? `${base}.kit.gen.ts` : null;
    const gen = (what) => `// GENERATED by tools/gen-registry.js: ${what} — do not edit.\n`;
    if (kit) files[`src/components/${kit}`] = gen(`the building blocks shown on ${page}`) + blocks.map((c) => `export * from "./${c.folder}/index.ts";\n`).join("") +
      demoKits.map((k) => `export * from "./${k}/demo-kit.tsx";\n`).join("");
    for (const { name, members } of parts) {
      // *.demos.gen.ts: the showcase config lets these stay small lazy files (chunks.allow), never joining the registry
      const file = `${name}.demos.gen.ts`;
      members.forEach((c, j) => groupOf.set(c.folder, { file, j }));
      files[`src/components/${file}`] = gen(`the component folders shown on ${page}`) + (kit ? `export * from "./${kit}";\n` : "") +
        members.map((c, j) => `import * as d${j} from "./${c.folder}/demo.tsx";\nimport * as p${j} from "./${c.folder}/playground.ts";\n`).join("") +
        `export { ${members.map((_, j) => `d${j}, p${j}`).join(", ")} };\n`;
    }
  }
  // a component with its own entry is shown statically on its page: no lazy loader here (a lazy demo would be a part
  // carrying the whole feature), the page imports demo.tsx and playground.ts itself
  const loader = (c, kind, file) => { if (c.meta?.entry) return `() => ownPage("${nameOf(c)}")`; const g = groupOf.get(c.folder); return g ? `() => import("./${g.file}").then((m) => m.${kind}${g.j})` : `() => import("./${c.folder}/${file}")`; };
  files["src/components/registry.gen.ts"] = HEAD + `import type { ComponentMeta, PlaygroundSpec } from "./meta.ts";\n` +
    list.map((c, i) => `import m${i} from "./${c.folder}/meta.ts";\n`).join("") +
    `\nexport interface RegistryEntry { folder: string; meta: ComponentMeta; /** First code block of docs.md (the Code tab). */ code: string; demo: () => Promise<{ default: (p: { values: never }) => unknown; code?: string }>; playground: () => Promise<{ default: PlaygroundSpec<never> }> }\n` +
    (list.some((c) => c.meta?.entry) ? `const ownPage = (name: string): Promise<never> => Promise.reject(new Error(\`\${name} has its own entry: its page imports the demo\`));\n` : "") +
    `/** Every component folder: meta, Code-tab snippet and lazy demo / playground loaders. */\nexport const registry: readonly RegistryEntry[] = [\n` +
    list.map((c, i) => `  { folder: "${c.folder}", meta: m${i}, code: ${JSON.stringify(firstCode(c.docs))}, demo: ${loader(c, "d", "demo.tsx")}, playground: ${loader(c, "p", "playground.ts")} },\n`).join("") + `];\n`;
  // the showcase card's catalogue: only what a card draws (name, summary, parts, the page of each part, the Code tab) and
  // the lazy loaders. No meta.ts imports: every page with a component card loads this file, the full metas weigh ~40 KB
  // (minified) that no card reads
  // The Code-tab snippets are their own lazy module (cards-code.gen.ts), loaded on the first click on a Code tab. A grouped
  // demo module is one loader shared by its cards (L(group, index)); a folder of its own keeps its two imports.
  const groups = [...new Set([...groupOf.values()].map((g) => g.file))];
  // w: the component's own page: the showcase page that draws its <ComponentDemo> (sections.gen.ts, read from the
  // page sources, so a moved demo moves the link), else the page named in meta.showcase
  const secFile = join(root, "examples/showcase/src/sections.gen.ts");
  const sections = existsSync(secFile) ? JSON.parse(/SECTIONS: Section\[\] = (\[.*\]);/s.exec(readFileSync(secFile, "utf8"))?.[1] ?? "[]") : [];
  const ownPage = (c) => sections.find((x) => x.id === `c-${c.folder.split("/").join("-")}`)?.path ?? c.meta?.showcase;
  const pick = (c) => ({ f: c.folder, n: nameOf(c), s: c.meta?.summary ?? "", ...(c.meta?.composedOf?.length ? { p: c.meta.composedOf } : {}), ...(ownPage(c) ? { w: ownPage(c) } : {}) });
  const load = (c) => {
    if (c.meta?.entry) return `...E`;
    const g = groupOf.get(c.folder);
    return g ? `...L(${groups.indexOf(g.file)}, ${g.j})` : `demo: () => import("./${c.folder}/demo.tsx"), playground: () => import("./${c.folder}/playground.ts")`;
  };
  files["src/components/cards.gen.ts"] = HEAD + `import type { PlaygroundSpec } from "./meta.ts";\n` +
    `\n/** f: folder, n: name, s: summary, p: composedOf, w: showcase page (the Code tab: cardCode(folder)). */\n` +
    `export interface CardEntry { f: string; n: string; s: string; p?: readonly string[]; w?: string; demo: () => Promise<{ default: (p: { values: never }) => unknown; code?: string }>; playground: () => Promise<{ default: PlaygroundSpec<never> }> }\n` +
    `type Mod = Record<string, { default: never }>;\nconst G: (() => Promise<Mod>)[] = [${groups.map((f) => `() => import("./${f}") as Promise<never>`).join(", ")}];\n` +
    `const L = (i: number, j: number) => ({ demo: () => G[i]!().then((m) => m[\`d\${j}\`]!), playground: () => G[i]!().then((m) => m[\`p\${j}\`]!) });\n` +
    (list.some((c) => c.meta?.entry) ? `const own = (): Promise<never> => Promise.reject(new Error("this component has its own entry: its page imports the demo"));\nconst E = { demo: own, playground: own };\n` : "") +
    `/** Every component folder as a showcase card needs it (registry.gen.ts has the full meta). */\nexport const cards: readonly CardEntry[] = [\n` +
    list.map((c) => `  { ${JSON.stringify(pick(c)).slice(1, -1)}, ${load(c)} },\n`).join("") + `];\n` +
    `/** The Code-tab snippet of a folder (one lazy module for every card). */\nexport const cardCode = (folder: string): Promise<string> => import("./cards-code.gen.ts").then((m) => m.code[folder] ?? "");\n`;
  files["src/components/cards-code.gen.ts"] = HEAD + `export const code: Record<string, string> = {\n` +
    list.map((c) => `  ${JSON.stringify(c.folder)}: ${JSON.stringify(firstCode(c.docs))},\n`).join("") + `};\n`;

  // catalogue by category (menu order), "composed of" links to the parts
  const byName = new Map(list.map((c) => [nameOf(c), c]));
  const part = (n) => (byName.has(n) ? `[${n}](#${anchor(n)})` : n);
  const row = (c, link) => `| ${nameOf(c)} | ${c.meta?.status ?? "?"} | ${c.meta?.summary ?? firstPara(c.docs)} | ${(c.meta?.composedOf ?? []).map(link ? part : (n) => n).join(", ") || "—"} |`;
  const filled = cats.filter((cat) => list.some((c) => c.category === cat.id));
  const table = (link) => filled.map((cat) => `### ${cat.title} — \`hadi-march/${cat.id}\`\n\n| Component | Status | What | Composed of |\n|---|---|---|---|\n` +
    list.filter((c) => c.category === cat.id).map((c) => row(c, link)).join("\n") + "\n").join("\n");
  files["docs/components.md"] = `<!-- GENERATED by tools/gen-registry.js from src/components/<category>/<name>/docs.md and meta.ts — do not edit. -->\n# Components\n\n` +
    `Grouped by category (src/components/categories.ts). Each category is a subpath: \`import { Chip } from "hadi-march/actions"\`; ` +
    `\`hadi-march/ui\` re-exports every component.\n\n${table(true)}\n` +
    list.map((c) => `## ${nameOf(c)}\n\n${firstPara(c.docs)}\n\n` +
      ((c.meta?.composedOf ?? []).length ? `Composed of: ${c.meta.composedOf.map(part).join(", ")}\n\n` : "") +
      `\`\`\`tsx\n${firstCode(c.docs)}\n\`\`\`\n\nFull page: src/components/${c.folder}/docs.md\n`).join("\n");
  const ai = readFileSync(join(root, "AI_INSTRUCTIONS.md"), "utf8");
  const block = `<!-- components:begin (generated by tools/gen-registry.js) -->\n${table(false)}<!-- components:end -->`;
  files["AI_INSTRUCTIONS.md"] = /<!-- components:begin[\s\S]*?<!-- components:end -->/.test(ai) ? ai.replace(/<!-- components:begin[\s\S]*?<!-- components:end -->/, block) : `${ai.trimEnd()}\n\n## Component catalogue (folders in src/components)\n\n${block}\n`;

  // subpaths: hadi-march/<category>; an older module of the same name re-exports the category barrel
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  let changed = false;
  for (const cat of cats) {
    const own = OWN_MODULE[cat.id];
    if (own) {
      const line = `export * from "../components/${cat.id}/index.ts";`;
      const text = readFileSync(join(root, own), "utf8");
      if (!text.includes(line)) files[own] = `${text.trimEnd()}\n// components of the "${cat.id}" category (src/components/${cat.id}, generated barrel)\n${line}\n`;
    } else if (pkg.exports[`./${cat.id}`] !== `./src/components/${cat.id}/index.ts`) {
      pkg.exports[`./${cat.id}`] = `./src/components/${cat.id}/index.ts`;
      changed = true;
    }
  }
  if (changed) files["package.json"] = JSON.stringify(pkg, null, 2) + "\n";
  return { files, list };
}

/** Exported names of hadi-march, hadi-march/ui, hadi-march/router and hadi-march/table (a part named in composedOf may still live there while folders move). */
function uiExports(root) {
  const text = ["src/index.ts", "src/ui/index.ts", "src/forms/index.ts", "src/router/index.ts", "src/router/router.ts", "src/table/index.ts"].map((f) => readFileSync(join(root, f), "utf8")).join("\n");
  return new Set([
    ...[...text.matchAll(/^export\s*\{([^}]*)\}/gm)].flatMap((m) => m[1].split(",").map((s) => s.trim().split(/\s+as\s+/).pop()).filter(Boolean)),
    ...[...text.matchAll(/^export\s+(?:function|const|class)\s+([A-Z][\w$]*)/gm)].map((m) => m[1]),
  ]);
}

/** Folder problems: missing files, a missing or wrong category, composedOf rules (a composite names its parts, and
 *  every part is a registered component or an export of hadi-march/ui). */
export function shapeProblems(list, root = ROOT) {
  const out = (list.stray ?? []).map((f) => `src/components/${f}: not a category folder (src/components/categories.ts); move it to src/components/<category>/${f}/`);
  const names = new Set(list.map(nameOf));
  const ui = uiExports(root);
  for (const c of list) {
    for (const f of REQUIRED) if (!c.files.includes(f)) out.push(`${c.folder}: missing ${f}`);
    if (!c.files.some((f) => f.endsWith(".test.js"))) out.push(`${c.folder}: missing ${c.name}.test.js`);
    if (!c.meta) continue;
    if (!c.meta.category) out.push(`${c.folder}: meta.category is missing (one of src/components/categories.ts)`);
    else if (c.meta.category !== c.category) out.push(`${c.folder}: meta.category is "${c.meta.category}" but the folder is in ${c.category}/`);
    if (!Array.isArray(c.meta.composedOf)) { out.push(`${c.folder}: meta.composedOf must be an array`); continue; }
    if (c.category === "composite" && !c.meta.composedOf.length) out.push(`${c.folder}: a composite component names its parts in meta.composedOf`);
    for (const p of c.meta.composedOf) if (!names.has(p) && !ui.has(p)) out.push(`${c.folder}: composedOf "${p}" is not a component`);
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { files, list } = await generate();
  const problems = shapeProblems(list);
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const p = join(ROOT, rel);
    const now = existsSync(p) ? readFileSync(p, "utf8") : null;
    if (now === text) continue;
    if (check) { console.error(`✖ ${rel} is out of date: run node tools/gen-registry.js`); stale++; }
    else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); console.log(`✔ ${rel}`); }
  }
  // demo modules of an earlier slicing (fewer cards, a page renamed) go away
  const dir = join(ROOT, "src/components");
  for (const f of readdirSync(dir).filter((f) => (f.endsWith(".demos.gen.ts") || f.endsWith(".kit.gen.ts")) && !files[`src/components/${f}`])) {
    if (check) { console.error(`✖ src/components/${f} is stale: run node tools/gen-registry.js`); stale++; }
    else { unlinkSync(join(dir, f)); console.log(`✖ removed src/components/${f}`); }
  }
  for (const p of problems) console.error(`✖ ${p}`);
  if (stale || problems.length) process.exit(1);
  console.log(`${list.length} component folder(s)${check ? ": up to date" : ""}`);
}

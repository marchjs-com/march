#!/usr/bin/env node
// Writes the shared files from the component folders (src/components/<name>/), so nobody edits them by hand and
// parallel branches that add folders do not conflict:
//   src/components/index.ts       barrel (re-exported by hadi-march/ui)
//   src/components/registry.gen.ts  catalogue: name, folder, meta, lazy demo / playground loaders (showcase, tools)
//   docs/components.md            component catalogue for people and AI (from each docs.md + meta.ts)
//   AI_INSTRUCTIONS.md            the catalogue table between the <!-- components:begin/end --> markers
//   node tools/gen-registry.js          write
//   node tools/gen-registry.js --check  fail (exit 1) when a written file is out of date
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const DIR = join(ROOT, "src/components");
const REQUIRED = ["index.ts", "docs.md", "demo.tsx", "playground.ts", "meta.ts"];

/** Component folders with their meta (sorted by folder name). */
export async function components(root = ROOT) {
  const dir = join(root, "src/components");
  if (!existsSync(dir)) return [];
  const out = [];
  for (const folder of readdirSync(dir).sort()) {
    const p = join(dir, folder);
    if (!statSync(p).isDirectory()) continue;
    const meta = existsSync(join(p, "meta.ts")) ? (await import(pathToFileURL(join(p, "meta.ts")).href)).default : null;
    out.push({ folder, meta, files: readdirSync(p), docs: existsSync(join(p, "docs.md")) ? readFileSync(join(p, "docs.md"), "utf8") : "" });
  }
  return out;
}

const HEAD = "// GENERATED by tools/gen-registry.js from src/components/*/ — do not edit.\n";
const firstCode = (md) => md.match(/```\w*\n([\s\S]*?)```/)?.[1].trim() ?? "";
const firstPara = (md) => md.split(/\n\n/).find((b) => b.trim() && !b.startsWith("#") && !b.startsWith("```"))?.replace(/\s+/g, " ").trim() ?? "";

/** The generated files' contents, keyed by path relative to the repo. */
export async function generate(root = ROOT) {
  const list = await components(root);
  const files = {};
  files["src/components/index.ts"] = HEAD + list.map((c) => `export * from "./${c.folder}/index.ts";\n`).join("");
  files["src/components/registry.gen.ts"] = HEAD + `import type { ComponentMeta, PlaygroundSpec } from "./meta.ts";\n` +
    list.map((c, i) => `import m${i} from "./${c.folder}/meta.ts";\n`).join("") +
    `\nexport interface RegistryEntry { folder: string; meta: ComponentMeta; /** First code block of docs.md (the Code tab). */ code: string; demo: () => Promise<{ default: (p: { values: never }) => unknown; code?: string }>; playground: () => Promise<{ default: PlaygroundSpec<never> }> }\n` +
    `export const registry: readonly RegistryEntry[] = [\n` +
    list.map((c, i) => `  { folder: "${c.folder}", meta: m${i}, code: ${JSON.stringify(firstCode(c.docs))}, demo: () => import("./${c.folder}/demo.tsx"), playground: () => import("./${c.folder}/playground.ts") },\n`).join("") + `];\n`;
  const rows = list.map((c) => `| ${c.meta?.name ?? c.folder} | ${c.meta?.status ?? "?"} | ${c.meta?.summary ?? firstPara(c.docs)} | ${(c.meta?.composedOf ?? []).join(", ") || "—"} |`);
  const table = `| Component | Status | What | Composed of |\n|---|---|---|---|\n${rows.join("\n")}\n`;
  files["docs/components.md"] = `<!-- GENERATED by tools/gen-registry.js from src/components/*/docs.md and meta.ts — do not edit. -->\n# Components\n\n${table}\n` +
    list.map((c) => `## ${c.meta?.name ?? c.folder}\n\n${firstPara(c.docs)}\n\n\`\`\`tsx\n${firstCode(c.docs)}\n\`\`\`\n\nFull page: src/components/${c.folder}/docs.md\n`).join("\n");
  const ai = readFileSync(join(root, "AI_INSTRUCTIONS.md"), "utf8");
  const block = `<!-- components:begin (generated by tools/gen-registry.js) -->\n${table}<!-- components:end -->`;
  files["AI_INSTRUCTIONS.md"] = /<!-- components:begin[\s\S]*?<!-- components:end -->/.test(ai) ? ai.replace(/<!-- components:begin[\s\S]*?<!-- components:end -->/, block) : `${ai.trimEnd()}\n\n## Component catalogue (folders in src/components)\n\n${block}\n`;
  return { files, list };
}

/** Folder shape problems: missing files, meta without composedOf (complex components must name what they reuse). */
export function shapeProblems(list) {
  const out = [];
  for (const c of list) {
    for (const f of REQUIRED) if (!c.files.includes(f)) out.push(`${c.folder}: missing ${f}`);
    if (!c.files.some((f) => f.endsWith(".test.js"))) out.push(`${c.folder}: missing ${c.folder}.test.js`);
    if (c.meta && !Array.isArray(c.meta.composedOf)) out.push(`${c.folder}: meta.composedOf must be an array`);
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { files, list } = await generate();
  const problems = shapeProblems(list);
  let stale = 0;
  for (const [rel, text] of Object.entries(files)) {
    const p = join(ROOT, rel);
    const now = existsSync(p) ? readFileSync(p, "utf8") : null;
    if (now === text) continue;
    if (check) { console.error(`✖ ${rel} is out of date: run node tools/gen-registry.js`); stale++; }
    else { writeFileSync(p, text); console.log(`✔ ${rel}`); }
  }
  for (const p of problems) console.error(`✖ ${p}`);
  if (stale || problems.length) process.exit(1);
  console.log(`${list.length} component folder(s)${check ? ": up to date" : ""}`);
}

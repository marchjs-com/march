#!/usr/bin/env node
// Writes src/css/themes.css from src/theme/presets.ts (the built-in themes). Run after changing a preset:
//   node tools/gen-themes.js          (--check: exit 1 when the file is stale; used by the tests)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { THEMES, DEFAULT_THEME, themeCss } from "../src/theme/presets.ts";

const out = fileURLToPath(new URL("../src/css/themes.css", import.meta.url));
export function render() {
  return `/* HADI March built-in themes. GENERATED by tools/gen-themes.js from src/theme/presets.ts — do not edit by hand.
   Pick one with setColorTheme("id") (sets data-hm-theme on <html>); the default (${DEFAULT_THEME}) also applies without the attribute. */
${THEMES.map((t) => themeCss(t, t.id === DEFAULT_THEME)).join("\n")}`;
}
const css = render();
if (process.argv.includes("--check")) {
  const ok = existsSync(out) && readFileSync(out, "utf8") === css;
  if (!ok) { console.error("✖ src/css/themes.css is stale: node tools/gen-themes.js"); process.exit(1); }
} else { writeFileSync(out, css); console.log(`✔ ${out} (${THEMES.length} themes)`); }

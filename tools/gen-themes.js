#!/usr/bin/env node
// Generates the theme stylesheets from src/theme/presets.ts (run after changing a preset; --check: exit 1 when stale):
//   src/css/themes/<id>.css   one file per theme; the default (hadi) is imported by tokens.css, the others are loaded on
//                             demand by setColorTheme() (<link rel="stylesheet">, `march build` copies them to dist/themes/)
//   src/css/themes.css        every theme at once (galleries, apps without the build step)
//   src/ui/theme-swatches.css the few colors ThemePicker/ThemeSwatch need to preview themes that are not loaded yet
//   src/theme/names.ts        ids, names and descriptions for pickers (without the color data)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { THEMES, DEFAULT_THEME, themeCss } from "../src/theme/presets.ts";

const at = (p) => fileURLToPath(new URL(`../src/${p}`, import.meta.url));
const HEAD = (what) => `/* March — ${what}. GENERATED by tools/gen-themes.js from src/theme/presets.ts; do not edit by hand. */\n`;

function swatchCss() {
  const vars = (c) => `--hm-bg: ${c.bg}; --hm-border: ${c.border}; --hm-primary-solid: ${c.solid}; --hm-cat-1: ${c.cat[0]}; --hm-cat-2: ${c.cat[1]};`;
  const out = [];
  for (const t of THEMES) {
    const s = `.hm-swatch[data-hm-theme="${t.id}"]`;
    out.push(`${s} { ${vars(t.alwaysDark ? t.dark : t.light)} }`);
    out.push(`@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) ${s} { ${vars(t.dark)} } }`);
    out.push(`:root[data-theme="dark"] ${s} { ${vars(t.dark)} }`);
  }
  return HEAD("theme previews for ThemePicker / ThemeSwatch") + out.join("\n") + "\n";
}

export function render() {
  const files = {};
  for (const t of THEMES) files[`css/themes/${t.id}.css`] = HEAD(`theme "${t.name}"`) + themeCss(t, t.id === DEFAULT_THEME);
  files["css/themes.css"] = HEAD("every built-in theme in one file") + THEMES.map((t) => `@import "./themes/${t.id}.css";\n`).join("");
  files["ui/theme-swatches.css"] = swatchCss();
  files["theme/names.ts"] = `// GENERATED by tools/gen-themes.js from presets.ts: the built-in themes' names only (runtime pickers stay small).\n`
    + `export const DEFAULT_THEME = ${JSON.stringify(DEFAULT_THEME)};\n`
    + `export const THEME_NAMES: readonly { id: string; name: string; description?: string }[] = ${JSON.stringify(THEMES.map(({ id, name, description }) => ({ id, name, description })), null, 2)};\n`;
  return files;
}

const files = render();
if (process.argv.includes("--check")) {
  const stale = Object.entries(files).filter(([p, css]) => !existsSync(at(p)) || readFileSync(at(p), "utf8") !== css).map(([p]) => p);
  if (stale.length) { console.error(`✖ stale theme files: ${stale.join(", ")} (node tools/gen-themes.js)`); process.exit(1); }
} else {
  mkdirSync(at("css/themes"), { recursive: true });
  for (const [p, css] of Object.entries(files)) writeFileSync(at(p), css);
  console.log(`✔ ${Object.keys(files).length} theme files`);
}

#!/usr/bin/env node
// What the compiler needs to turn an icon written by name (`icon="lucide:heart"`) into an import (compiler/icon-names.js):
//   compiler/icon-names.gen.js  the pack ids, March's icons (name → export) and the pack names whose export is not
//                               exportName(name) (a name two files share: "arrow-down-01" → arrowDown012)
//   src/icons/names.gen.ts      the same as types: MarchIconName ("chevron-down" | …) and IconPackId ("lucide" | …), for
//                               IconType (src/icons/types.ts)
// Read from src/icons/set.ts (March's) and src/icons/packs/<id>/index.js (made by `march icons add`).
// `--check` fails when the file is stale (test/icon-names.test.js runs it).
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { exportName } from "../compiler/icon-names.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const OUT = "compiler/icon-names.gen.js", TYPES = "src/icons/names.gen.ts";
const march = [...readFileSync(`${root}src/icons/set.ts`, "utf8").matchAll(/^export const (\w+) = \/\* @__PURE__ \*\/ i\("([^"]+)"/gm)].map(([, exp, name]) => [name, exp]);
const packsDir = `${root}src/icons/packs`;
const ids = existsSync(packsDir) ? readdirSync(packsDir).filter((id) => existsSync(`${packsDir}/${id}/index.js`)).sort() : [];
const except = [];
for (const id of ids) {
  for (const [, exp, name] of readFileSync(`${packsDir}/${id}/index.js`, "utf8").matchAll(/^export const (\w+) = \/\* @__PURE__ \*\/ i\("([^"]+)"/gm))
    if (exportName(name) !== exp) except.push([`${id}:${name}`, exp]);
}
const J = JSON.stringify;
const text = `// GENERATED by tools/gen-icon-names.js from src/icons/set.ts and src/icons/packs — do not edit.
/** The icon packs \`march/icons/<id>\` has. */
export const ICON_PACKS = ${J(ids)};
/** March's icons: name → export ("chevron-down" → chevronDown). */
export const MARCH_ICONS = {${march.map(([n, e]) => `${J(n)}:${J(e)}`).join(",")}};
/** Pack icons whose export is not exportName(name). */
export const ICON_EXCEPTIONS = {${except.map(([k, e]) => `${J(k)}:${J(e)}`).join(",")}};
`;
const types = `// GENERATED by tools/gen-icon-names.js from src/icons/set.ts and src/icons/packs — do not edit.
/** A March icon's name ("chevron-down"): \`icon="chevron-down"\` in an icon prop is that icon. */
export type MarchIconName = ${march.map(([n]) => J(n)).join(" | ")};
/** An icon pack of march/icons/<id> ("lucide:heart" in an icon prop is that pack's icon). */
export type IconPackId = ${ids.map((id) => J(id)).join(" | ")};
`;
const read = (f) => { try { return readFileSync(root + f, "utf8"); } catch { return null; } };
const outs = [[OUT, text], [TYPES, types]];
if (process.argv.includes("--check")) {
  const stale = outs.filter(([f, t]) => read(f) !== t).map(([f]) => f);
  if (stale.length) { console.error(`✖ ${stale.join(", ")} stale: node tools/gen-icon-names.js`); process.exit(1); }
  console.log(`✔ ${outs.map(([f]) => f).join(", ")} up to date`);
} else {
  for (const [f, t] of outs) if (read(f) !== t) writeFileSync(root + f, t);
  console.log(`✔ ${OUT}, ${TYPES}: ${ids.length} packs, ${march.length} March icons, ${except.length} exceptions`);
}

// Writes the Google Fonts catalog FontPicker shows (src/components/composite/font-picker/google-catalog.gen.ts) from
// the public metadata list. Only names and facts (category, weights, italics, subsets, date added) are kept, in a
// compact text form; no font file is copied. Open-licensed families only; brand fonts (other than Noto) are left out, and families with no upright style.
//   node tools/gen-font-catalog.mjs            fetch the list and write the file
//   node tools/gen-font-catalog.mjs <file>     read a saved copy of the list instead
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://fonts.google.com/metadata/fonts";
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src/components/composite/font-picker/google-catalog.gen.ts");
const CATEGORIES = ["Sans Serif", "Serif", "Display", "Handwriting", "Monospace"];
const EPOCH = Date.UTC(2010, 0, 1);

const text = process.argv[2] ? readFileSync(process.argv[2], "utf8") : await (await fetch(SOURCE)).text();
const list = JSON.parse(text.replace(/^\)\]\}'\n?/, "")).familyMetadataList
  .filter((f) => f.isOpenSource !== false && (!f.isBrandFont || f.isNoto) && /^[A-Za-z0-9 ]+$/.test(f.family) && CATEGORIES.includes(f.category) && mask(Object.keys(f.fonts), false))
  .sort((a, b) => (a.popularity ?? 1e9) - (b.popularity ?? 1e9));

// subsets by how many families have them: the common ones get one-character codes
const count = new Map();
for (const f of list) for (const s of f.subsets) if (s !== "menu") count.set(s, (count.get(s) ?? 0) + 1);
const subsets = [...count].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).map((x) => x[0]);
const code = (i) => (i < 36 ? i.toString(36) : `~${i.toString(36).padStart(2, "0")}`);
function mask(keys, italic) {
  let m = 0;
  for (const k of keys) { const it = k.endsWith("i"), w = Number.parseInt(k, 10); if (it === italic && w >= 100 && w <= 900 && w % 100 === 0) m |= 1 << (w / 100 - 1); }
  return m;
}

const lines = list.map((f) => {
  const keys = Object.keys(f.fonts), up = mask(keys, false), it = mask(keys, true);
  const days = Math.max(0, Math.round((Date.parse(f.dateAdded ?? "2010-01-01") - EPOCH) / 864e5));
  return [f.family, CATEGORIES.indexOf(f.category), up.toString(36), it === up ? "=" : it ? it.toString(36) : "", f.subsets.filter((s) => s !== "menu").map((s) => code(subsets.indexOf(s))).join(""), days.toString(36)].join("|");
});

writeFileSync(out, `// GENERATED by tools/gen-font-catalog.mjs from ${SOURCE}: do not edit by hand.
// ${list.length} open-licensed families, most used first. A line: name|category|upright weights|italic weights|subsets|day added
// (weights: bit masks 100…900 in base 36, "=": the same as upright; subsets: codes into SUBSETS; days since 2010-01-01).
/** Subset names the codes in FONTS point at. */
export const SUBSETS = ${JSON.stringify(subsets.join(" "))};
/** The catalog, one family per line. */
export const FONTS = ${JSON.stringify(lines.join("\n"))};
`);
console.log(`${list.length} families, ${subsets.length} subsets → ${out}`);

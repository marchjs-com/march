#!/usr/bin/env node
// src/components/layout/grid/grid.css is generated: the balance table and the span mode are long, regular rule sets.
//   node tools/gen-grid.js           write it
//   node tools/gen-grid.js --check   fail when it is stale (test/grid.test.js)
//
// Span mode (`<Grid cols={4} fill="stretch" equal>`): the grid has 60 thin columns (60 is divisible by 1–6), every item
// spans 60 / k of them, k being the number of columns that fit. The last row is found with :nth-child / :nth-last-child
// and its items span 60 / r (r = items in that row), so it fills the row — while `grid-auto-rows: 1fr` (`equal`) keeps
// every row as tall as the tallest. k follows the container's own width (container queries) for three minimum column
// widths (minCol 9rem / 13rem / 17rem). Column gaps are margins on the items (a gap between 60 tracks would not fit).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../src/components/layout/grid/grid.css", import.meta.url));
const BASE = 60;
export const MIN_COLS = [9, 13, 17]; // rem; Grid maps minCol to the nearest
const GAP = 1; // rem assumed between columns when computing the breakpoints

const L = [];
const add = (s) => L.push(s);
add("/* HADI March — Grid. GENERATED by tools/gen-grid.js — do not edit by hand. */");
add("/* Fixed or automatic columns (display.css); fill / balance in flex mode; equal height + fill in span mode. */");
add(".hm-grid { gap: var(--hm-grid-gap, var(--hm-space-4)); }");
add(".hm-grid > * { min-width: 0; }");
add("/* a card wrapped in a grid cell (e.g. for an animation) still fills the cell: equal heights */");
add(".hm-grid > * > :only-child:is(.hm-card, .hm-link-card) { height: 100%; }");
for (let n = 0; n <= 8; n++) add(`.hm-grid-gap-${n} { --hm-grid-gap: var(--hm-space-${n}); }`);
add(".hm-grid-equal { grid-auto-rows: 1fr; }");

add("/* flex modes: columns are flex-basis fractions; --hm-cols is the declared (or balanced) count, capped on small screens */");
add("/* .hm-grid.hm-grid-flex: wins over display.css .hm-grid { display: grid } whatever order the CSS loads in */");
add(".hm-grid.hm-grid-flex { display: flex; flex-wrap: wrap; container: hm-grid / inline-size; }");
add(".hm-grid-flex > * { --hm-cols-cq: 99; --hm-cols-eff: min(var(--hm-cols, 2), var(--hm-cols-md, 99), var(--hm-cols-sm, 99), var(--hm-cols-cq));");
add("  flex: 0 1 max(min(var(--hm-grid-col-min, 9rem), 100%), (100% - (var(--hm-cols-eff) - 1) * var(--hm-grid-gap, var(--hm-space-4))) / var(--hm-cols-eff) - .1px); max-width: 100%; }");
add("/* the container's own width caps the columns (9rem minimum + 1rem gap each): a narrow box gets fewer, readable columns */");
for (const k of [5, 4, 3, 2, 1]) add(`@container hm-grid (width < ${(k + 1) * 9 + k}rem) { .hm-grid-flex > * { --hm-cols-cq: ${k}; } }`);
add(".hm-grid-flex-min > * { flex: 1 1 min(var(--hm-grid-min, 16rem), 100%); }");
add(".hm-grid-flex.hm-grid-fill-stretch > * { flex-grow: 1; }");
add(".hm-grid-flex.hm-grid-fill-last > :last-child { flex-grow: 1; }");
for (let c = 1; c <= 6; c++) add(`.hm-grid-c${c} { --hm-cols: ${c}; }`);
add("/* balance: rows = ceil(n / cols), columns = ceil(n / rows) */");
for (let c = 2; c <= 6; c++) for (let n = 2; n <= 24; n++) {
  const rows = Math.ceil(n / c), b = Math.ceil(n / rows);
  if (b !== c) add(`.hm-grid-balance.hm-grid-c${c}:has(> :nth-child(${n}):last-child) { --hm-cols: ${b}; }`);
}
add("/* separate caps per breakpoint so neither rule has to win on specificity */");
add("@media (max-width: 1024px) { .hm-grid-flex.hm-grid-c4, .hm-grid-flex.hm-grid-c5, .hm-grid-flex.hm-grid-c6 { --hm-cols-md: 2; } }");
add("@media (max-width: 640px) { .hm-grid-flex { --hm-cols-sm: 1; } .hm-grid-flex-min > * { flex-basis: 100%; } }");

add("/* span mode: 60 thin columns, items span 60/k; the last row's items span 60/r (fill) — see tools/gen-grid.js */");
add(".hm-grid-span { display: grid; grid-template-columns: repeat(60, minmax(0, 1fr)); column-gap: 0; row-gap: var(--hm-grid-gap, var(--hm-space-4));");
add("  container: hm-grid-span / inline-size; margin-inline: calc(var(--hm-grid-gap, var(--hm-space-4)) / -2); }");
add(".hm-grid-span > * { grid-column: span 60; margin-inline: calc(var(--hm-grid-gap, var(--hm-space-4)) / 2); }");
for (const m of MIN_COLS) for (let c = 1; c <= 6; c++) for (let k = 1; k <= c; k++) {
  const S = `.hm-grid-span.hm-gc-${c}.hm-gm-${m}`;
  const rules = [`${S} > * { grid-column: span ${BASE / k}; }`];
  for (let r = 1; r < k; r++) {
    const first = `${S}.hm-grid-fill-stretch > :nth-child(${k}n+1):nth-last-child(${r})`;
    rules.push(`${first}, ${first} ~ * { grid-column: span ${BASE / r}; }`);
    rules.push(`${S}.hm-grid-fill-last > :last-child:nth-child(${k}n+${r}) { grid-column: span ${BASE - (r - 1) * (BASE / k)}; }`);
  }
  // container width (rem) at which k columns of m rem (+ gaps) fit; the grid's negative margins add one gap
  const lo = k === 1 ? null : k * m + (k - 1) * GAP + GAP;
  const hi = k === c ? null : (k + 1) * m + k * GAP + GAP;
  const cond = [lo != null && `(width >= ${lo}rem)`, hi != null && `(width < ${hi}rem)`].filter(Boolean).join(" and ");
  add(cond ? `@container hm-grid-span ${cond} { ${rules.join(" ")} }` : rules.join(" "));
}

const css = `${L.join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(OUT, "utf8") !== css) { console.error("✖ src/components/layout/grid/grid.css is stale: node tools/gen-grid.js"); process.exit(1); }
  console.log("✔ grid.css up to date");
} else if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, css);
  console.log(`✔ src/components/layout/grid/grid.css (${L.length} lines, ${(css.length / 1024).toFixed(1)} KB)`);
}

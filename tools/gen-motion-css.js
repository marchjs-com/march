#!/usr/bin/env node
// One CSS file from motion keyframes registrations: node tools/gen-motion-css.js <module.ts> [out.css] [--presets]
// The module registers keyframes (keyframes(), defineMotion()); --presets adds the built-in ones (fadeUp, pop, spin…).
// Then `class="m-anim-fadeUp"` plays them with pure CSS — under the same global speed / pause control at runtime.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const args = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const engine = await import(new URL("../src/motion/engine/index.ts", import.meta.url).href);
if (process.argv.includes("--presets")) engine.installPresets();
if (args[0]) await import(pathToFileURL(resolve(args[0])).href);
const css = `/* generated by tools/gen-motion-css.js — do not edit */\n${engine.keyframesCss()}`;
if (args[1]) { writeFileSync(resolve(args[1]), css); console.log(`✔ ${args[1]} (${engine.keyframeNames().length} keyframes)`); }
else process.stdout.write(css);

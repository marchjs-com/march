#!/usr/bin/env node
// Showcase section index for the command palette: every demo section of every page (title, description, component,
// anchor) → examples/showcase/src/sections.gen.ts. The palette loads it lazily; picking one opens the page and scrolls
// to the section. Anchors: a ComponentDemo is "c-<folder>", any other Demo "d-<slug of its title>" (same slug as demo.tsx).
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const PAGES = join(ROOT, "examples/showcase/src/pages");
const OUT = join(ROOT, "examples/showcase/src/sections.gen.ts");

/** Same as demoSlug() in examples/showcase/src/demo.tsx. */
export const demoSlug = (s) => s.toLocaleLowerCase("tr").replace(/ı/g, "i").normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);

const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : /\.tsx$/.test(f) ? [p] : []; });
const attr = (tag, name) => { const m = new RegExp(`\\b${name}="([^"]*)"`).exec(tag); return m ? m[1].replace(/&quot;/g, "\"") : undefined; };

// page titles: `export const title = "…"` in the page, else the nav entry
const navSrc = existsSync(join(ROOT, "examples/showcase/src/nav.ts")) ? readFileSync(join(ROOT, "examples/showcase/src/nav.ts"), "utf8") : "";
const navTitle = (path) => { const m = new RegExp(`path: "${path.replace(/[/]/g, "\\/")}", title: "([^"]+)"`).exec(navSrc); return m?.[1]; };

const out = [];
for (const file of walk(PAGES)) {
  const rel = relative(PAGES, file).replace(/\\/g, "/").replace(/\.tsx$/, "");
  if (rel.startsWith("_") || rel.includes("/_")) continue;
  const path = rel === "home" ? "/" : `/${rel}`;
  const src = readFileSync(file, "utf8");
  const page = /export const title = "([^"]+)"/.exec(src)?.[1] ?? navTitle(path) ?? rel;
  for (const m of src.matchAll(/<(ComponentDemo|Demo)\b([^>]*?)\/?>/gs)) {
    const tag = m[2];
    const title = attr(tag, "title");
    const folder = m[1] === "ComponentDemo" ? attr(tag, "folder") : undefined;
    if (!title && !folder) continue;
    const id = attr(tag, "id") ?? (folder ? `c-${folder.split("/").join("-")}` : `d-${demoSlug(title)}`);
    out.push({ path, page, id, title: title ?? folder.split("/").pop(), desc: (attr(tag, "desc") ?? "").slice(0, 160), comp: folder ? folder.split("/").pop() : "" });
  }
}
out.sort((a, b) => a.path.localeCompare(b.path));
const body = `// GENERATED by tools/gen-sections.js from src/pages — do not edit.\nexport interface Section { path: string; page: string; id: string; title: string; desc: string; comp: string }\nexport const SECTIONS: Section[] = ${JSON.stringify(out)};\n`;
if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== body) writeFileSync(OUT, body);
console.log(`gen sections: ${out.length}`);

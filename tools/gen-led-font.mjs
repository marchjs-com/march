#!/usr/bin/env node
// The 5×7 LED font (src/components/media/pixel-font/glyphs.ts) from its drawings in tools/led-font/glyphs-5x7.txt.
// The text file is the source: a line with one character starts a glyph, then up to 8 rows of 5 "." / "#" (rows 0–6
// the body, row 7 descenders and cedillas; missing rows are blank). Edit a drawing there, then:
//   node tools/gen-led-font.mjs            write glyphs.ts
//   node tools/gen-led-font.mjs --check    exit 1 when glyphs.ts is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SRC = fileURLToPath(new URL("./led-font/glyphs-5x7.txt", import.meta.url));
const OUT = fileURLToPath(new URL("../src/components/media/pixel-font/glyphs.ts", import.meta.url));
const B32 = "0123456789abcdefghijklmnopqrstuv";

const glyphs = [];
for (const line of readFileSync(SRC, "utf8").split(/\r?\n/).filter(Boolean)) {
  if (/^[.#]{5}$/.test(line) && glyphs.length) { glyphs.at(-1).rows.push(line); continue; }
  if ([...line].length !== 1) throw new Error(`glyphs-5x7.txt: "${line}" is neither a character nor a row of 5`);
  glyphs.push({ ch: line, rows: [] });
}
let packed = "";
for (const g of glyphs) {
  if (g.rows.length > 8) throw new Error(`glyph ${g.ch}: more than 8 rows`);
  const rows = [...g.rows, ...Array(8 - g.rows.length).fill(".....")];
  packed += g.ch + rows.map((r) => B32[parseInt(r.replace(/#/g, "1").replace(/\./g, "0"), 2)]).join("");
}
const text = `// GENERATED by tools/gen-led-font.mjs from tools/led-font/glyphs-5x7.txt (own drawings, 5 columns × 8 rows: rows 0–6
// the body, row 7 descenders and cedillas; Turkish capitals with a mark are drawn one row shorter so the mark fits).
// Each glyph: its character, then 8 rows in base 32 (bit 4 = the leftmost column). Do not edit: edit the drawings.
export const GLYPHS_5X7 = ${JSON.stringify(packed)};
`;
const now = readFileSync(OUT, "utf8");
if (process.argv.includes("--check")) {
  if (now !== text) { console.error("✖ glyphs.ts is out of date: node tools/gen-led-font.mjs"); process.exit(1); }
} else if (now !== text) writeFileSync(OUT, text);
console.log(`LED font: ${glyphs.length} glyphs`);

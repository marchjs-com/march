// File based routes: src/pages/index.jsx → "/", users/[id].jsx → "/users/:id", docs/[...slug].jsx → "/docs/*slug",
// files and folders starting with "_" are ignored. Generates routes.gen.js (lazy imports) and pages.d.ts (param types).
import { readdirSync, statSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, relative, sep, dirname } from "node:path";

export function routeOf(rel) {
  const parts = rel.replace(/\.(jsx|js)$/, "").split(/[\\/]/);
  const segs = parts.map((p) => (p === "index" ? "" : p.startsWith("[...") ? `*${p.slice(4, -1)}` : p.startsWith("[") ? `:${p.slice(1, -1)}` : p)).filter(Boolean);
  return `/${segs.join("/")}`;
}
export const paramsOf = (route) => [...route.matchAll(/[:*]([A-Za-z_]\w*)/g)].map((m) => m[1]);

export function scanPages(dir) {
  const out = [];
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      if (n.startsWith("_") || n.startsWith(".")) continue;
      const p = join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(jsx|js)$/.test(n)) out.push(relative(dir, p));
    }
  };
  if (existsSync(dir)) walk(dir);
  return out.sort();
}

export function genRoutes(pagesDir, outFile) {
  const files = scanPages(pagesDir);
  const relDir = relative(dirname(outFile), pagesDir).split(sep).join("/") || ".";
  const lines = files.map((f) => `  ${JSON.stringify(routeOf(f))}: () => import(${JSON.stringify(`./${relDir}/${f.split(sep).join("/")}`)}),`);
  const code = `// GENERATED by \`march gen routes\` from ${relDir}/ — do not edit.\nexport default {\n${lines.join("\n")}\n};\n`;
  if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== code) writeFileSync(outFile, code);
  const dts = `// GENERATED: route params per page file.\nexport interface PageParams {\n${files.map((f) => `  ${JSON.stringify(routeOf(f))}: { ${paramsOf(routeOf(f)).map((p) => `${p}: string`).join("; ")} };`).join("\n")}\n}\n`;
  const dtsFile = join(dirname(outFile), "pages.d.ts");
  if (!existsSync(dtsFile) || readFileSync(dtsFile, "utf8") !== dts) writeFileSync(dtsFile, dts);
  return files.map(routeOf);
}

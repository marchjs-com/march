// File based routes: src/pages/index.jsx → "/", users/[id].jsx → "/users/:id", docs/[...slug].jsx → "/docs/*slug".
// `_layout.jsx` (or .tsx) in a folder wraps every page below it (outermost first). Other files/folders starting with "_"
// are ignored. Generates routes.gen.js (lazy imports) and pages.d.ts (param types + typed navigate()/Link hrefs).
import { readdirSync, statSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, relative, sep, dirname } from "node:path";

const PAGE = /\.(jsx|tsx|js|ts)$/;
export function routeOf(rel) {
  const parts = rel.replace(PAGE, "").split(/[\\/]/);
  const segs = parts.map((p) => (p === "index" ? "" : p.startsWith("[...") ? `*${p.slice(4, -1)}` : p.startsWith("[") ? `:${p.slice(1, -1)}` : p)).filter(Boolean);
  return `/${segs.join("/")}`;
}
export const paramsOf = (route) => [...route.matchAll(/[:*]([A-Za-z_]\w*)/g)].map((m) => m[1]);

export function scanPages(dir) {
  const pages = [], layouts = new Map(); // folder (relative, "" = root) → layout file
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) { if (!n.startsWith("_") && !n.startsWith(".")) walk(p); continue; }
      if (!PAGE.test(n) || n.endsWith(".d.ts") || /\.test\./.test(n)) continue;
      const rel = relative(dir, p);
      if (/^_layout\./.test(n)) layouts.set(relative(dir, d).split(sep).join("/"), rel);
      else if (!n.startsWith("_") && !n.startsWith(".")) pages.push(rel);
    }
  };
  if (existsSync(dir)) walk(dir);
  return { pages: pages.sort(), layouts };
}

/** Layout files that wrap a page (root first). */
export function layoutsFor(rel, layouts) {
  const folders = rel.split(/[\\/]/).slice(0, -1);
  const out = [];
  for (let i = 0; i <= folders.length; i++) { const f = folders.slice(0, i).join("/"); if (layouts.has(f)) out.push(layouts.get(f)); }
  return out;
}

export function genRoutes(pagesDir, outFile) {
  const { pages, layouts } = scanPages(pagesDir);
  const relDir = relative(dirname(outFile), pagesDir).split(sep).join("/") || ".";
  const imp = (f) => `() => import(${JSON.stringify(`./${relDir}/${f.split(sep).join("/")}`)})`;
  const lines = pages.map((f) => {
    const ls = layoutsFor(f, layouts);
    return `  ${JSON.stringify(routeOf(f))}: ${ls.length ? `{ load: ${imp(f)}, layouts: [${ls.map(imp).join(", ")}] }` : imp(f)},`;
  });
  const code = `// GENERATED by \`march gen routes\` from ${relDir}/ — do not edit.\nexport default {\n${lines.join("\n")}\n};\n`;
  if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== code) writeFileSync(outFile, code);
  const routes = pages.map(routeOf);
  const dts = `// GENERATED by \`march gen routes\`: route params per page and typed hrefs for navigate()/<Link>.
export interface PageParams {
${routes.map((r) => `  ${JSON.stringify(r)}: { ${paramsOf(r).map((p) => `${p}: string`).join("; ")} };`).join("\n")}
}
declare module "hadi-march/router" {
  interface Register { routes: ${routes.length ? routes.map((r) => JSON.stringify(r)).join(" | ") : "never"} }
}
`;
  const dtsFile = join(dirname(outFile), "pages.d.ts");
  if (!existsSync(dtsFile) || readFileSync(dtsFile, "utf8") !== dts) writeFileSync(dtsFile, dts);
  return routes;
}

// OpenAPI 3 → March client + schemas, and a mock server that answers from the document's examples.
const camel = (s) => s.replace(/[^A-Za-z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^./, (c) => c.toLowerCase());

function fieldOf(prop, required) {
  const f = { required };
  const t = prop.type, fmt = prop.format;
  if (prop.enum) { f.type = "pick"; f.options = prop.enum; }
  else if (t === "boolean") f.type = "bool";
  else if (t === "integer") f.type = "int";
  else if (t === "number") f.type = "number";
  else if (t === "array") f.type = prop.items?.enum ? "multi" : "list";
  else if (t === "object") f.type = "json";
  else if (fmt === "email") f.type = "email";
  else if (fmt === "uri" || fmt === "url") f.type = "url";
  else if (fmt === "date") f.type = "date";
  else if (fmt === "date-time") f.type = "datetime";
  else if (fmt === "password") f.type = "password";
  else f.type = "text";
  if (prop.minimum != null) f.min = prop.minimum;
  if (prop.maximum != null) f.max = prop.maximum;
  if (prop.minLength != null) f.minLength = prop.minLength;
  if (prop.maxLength != null) f.maxLength = prop.maxLength;
  if (prop.items?.enum) f.options = prop.items.enum;
  if (prop.description) f.help = prop.description;
  if (prop.default !== undefined) f.default = prop.default;
  if (prop.readOnly) f.readonly = true;
  return f;
}

export function genApi(doc) {
  const out = ["// GENERATED by `march gen api` — do not edit.", 'import { schema } from "hadi-march/schema";', 'import { fetchJson } from "hadi-march/data";', ""];
  const base = doc.servers?.[0]?.url ?? "";
  out.push(`export const BASE = ${JSON.stringify(base)};`, "");
  for (const [name, s] of Object.entries(doc.components?.schemas ?? {})) {
    if (s.type !== "object") continue;
    const req = new Set(s.required ?? []);
    const fields = Object.fromEntries(Object.entries(s.properties ?? {}).map(([k, p]) => [k, fieldOf(p, req.has(k))]));
    out.push(`/** ${s.description ?? name} */`, `export const ${name}Schema = schema(${JSON.stringify(fields, null, 2)});`, "");
  }
  out.push("export const api = {");
  for (const [path, item] of Object.entries(doc.paths ?? {})) {
    for (const [method, op] of Object.entries(item)) {
      if (!/^(get|post|put|patch|delete)$/.test(method)) continue;
      const id = camel(op.operationId ?? `${method} ${path}`);
      const params = [...path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
      const hasBody = !!op.requestBody;
      const sig = [...params, ...(hasBody ? ["body"] : []), "query = {}", "opts = {}"].join(", ");
      const url = "`${BASE}" + path.replace(/\{(\w+)\}/g, "${encodeURIComponent($1)}") + "${qs(query)}`";
      out.push(`  /** ${method.toUpperCase()} ${path}${op.summary ? ` — ${op.summary}` : ""} */`);
      out.push(`  ${id}: (${sig}) => fetchJson(${url}, { method: ${JSON.stringify(method.toUpperCase())}${hasBody ? ", body" : ""}, ...opts }),`);
    }
  }
  out.push("};", "", "function qs(q) { const s = new URLSearchParams(Object.entries(q).filter(([, v]) => v != null && v !== \"\")).toString(); return s ? `?${s}` : \"\"; }", "");
  return out.join("\n");
}

function exampleOf(media, doc) {
  if (!media) return null;
  if (media.example !== undefined) return media.example;
  const ex = media.examples && Object.values(media.examples)[0];
  if (ex?.value !== undefined) return ex.value;
  return sample(media.schema, doc, 0);
}
function sample(s, doc, depth) {
  if (!s || depth > 5) return null;
  if (s.$ref) return sample(doc.components?.schemas?.[s.$ref.split("/").pop()], doc, depth + 1);
  if (s.example !== undefined) return s.example;
  if (s.enum) return s.enum[0];
  switch (s.type) {
    case "object": return Object.fromEntries(Object.entries(s.properties ?? {}).map(([k, v]) => [k, sample(v, doc, depth + 1)]));
    case "array": return [sample(s.items, doc, depth + 1)];
    case "integer": case "number": return s.minimum ?? 1;
    case "boolean": return true;
    default: return s.format === "date-time" ? new Date(0).toISOString() : s.format === "date" ? "2026-01-01" : "string";
  }
}

/** Mock API for `march dev --mock spec.json`: answers with examples (or schema samples) for every documented path. */
export function mockHandler(doc) {
  const base = new URL(doc.servers?.[0]?.url ?? "/api", "http://x").pathname.replace(/\/$/, "") || "/api";
  const routes = [];
  for (const [path, item] of Object.entries(doc.paths ?? {})) for (const [method, op] of Object.entries(item)) {
    if (!/^(get|post|put|patch|delete)$/.test(method)) continue;
    const re = new RegExp(`^${base}${path.replace(/\{\w+\}/g, "[^/]+")}$`);
    const [status, resp] = Object.entries(op.responses ?? { 200: {} }).find(([c]) => /^2/.test(c)) ?? ["200", {}];
    routes.push({ method: method.toUpperCase(), re, status: Number(status) || 200, body: exampleOf(resp.content?.["application/json"], doc) });
  }
  return {
    base,
    handle(req, res, url) {
      const r = routes.find((x) => x.method === req.method && x.re.test(url.pathname));
      res.writeHead(r ? r.status : 404, { "content-type": "application/json" });
      res.end(JSON.stringify(r ? r.body : { message: `No mock for ${req.method} ${url.pathname}` }));
    },
  };
}
